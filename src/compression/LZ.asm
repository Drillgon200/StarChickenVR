;struct DLZ2DecodeCallArgs {
;	Byte* writePtr;
;	U64 matchOrLiteralRunCount;
;	Byte* matchOrLiteralSwitches;
;	Byte* literals;
;	Byte* lengths;
;	Byte* offsets;
;};
dlz2_decode PROC
	; save callee preserved GPRs
	push rbx
	push rbp
	push rdi
	push rsi
	push r12
	push r13
	push r14
	push r15

	mov rax, [rcx] ; writePtr
	mov rbx, [rcx + 8] ; iterationCount
	mov rdx, [rcx + 16] ; match/literal bits
	mov rbp, [rcx + 24] ; literals
	mov rsi, [rcx + 32] ; lengths
	mov rdi, [rcx + 40] ; offsets

	movzx ecx, byte ptr [rdx]
	inc rdx
	cmp rbx, 7
	jbe last7
	push rbx
	shr rbx, 3

DECODE_STEP macro matchOrLitBitIdx
	movzx r8, r12b
	shr r12, 8
	movzx r10, r13w
	shr r13, 16
	mov r9, rax
	sub r9, r10
	test ecx, 1 SHL matchOrLitBitIdx
	cmovz r9, rbp ; copy src
	vmovups ymm0, [r9]
	vmovups [rax], ymm0
	lea r9, [rbp + r8]
	cmovz rbp, r9
	add rax, r8
endm

; This is so much more annoying than it seems like it should be
; Why does decoding a variable length integer need such a long dependency chain?
; Three table lookups? A dependency chain with two loads? Surely this can be better.
; Maybe I should just get rid of the match/literal switch bits and always write both in one packet like other fast LZ algorithms.
LENGTH_DECODE_STEP macro
	mov r9, rcx
	and r9, 0Fh
	lea r8, [pdepFlagExtendedTable]
	mov r8, [r8 + r9 * 8]
	mov r13, [rdi]
	mov r14, 0101010101010101h
	pext r14, r13, r14
	shl r14, 3
	lea r15, [pdepMaskTable]
	mov r15, [r15 + r14]
	pdep r13, r13, r15
	pdep r13, r13, r8
	mov r15, 0FFFEFFFEFFFEFFFEh
	and r13, r15
	shr r13, 1

	popcnt r9, r9
	add r14, r9
	lea r9, [lengthBytesConsumedTable]
	movzx r14, byte ptr [r9 + r14]
	add rdi, r14
endm

decodeLoop:
	mov r12, [rsi] ; 8 lengths

	LENGTH_DECODE_STEP
	DECODE_STEP 0
	DECODE_STEP 1
	DECODE_STEP 2
	DECODE_STEP 3
	shr ecx, 4
	LENGTH_DECODE_STEP
	DECODE_STEP 0
	DECODE_STEP 1
	DECODE_STEP 2
	DECODE_STEP 3

	movzx ecx, byte ptr [rdx]
	inc rdx
	add rsi, 8
	dec rbx
	jnz decodeLoop

	pop rbx
	and ebx, 7
last7:
	test ebx, ebx
	jz finished

	mov r12, [rsi] ; 8 lengths

	LENGTH_DECODE_STEP
	DECODE_STEP 0
	dec ebx
	jz finished
	DECODE_STEP 1
	dec ebx
	jz finished
	DECODE_STEP 2
	dec ebx
	jz finished
	DECODE_STEP 3
	dec ebx
	jz finished
